@pytest.mark.parametrize("text", EXPENSES)
def test_real_expense_is_caught(text):
    assert parse_message(text), f"пропустил настоящую трату: {text!r}"


@pytest.mark.parametrize("text", CHATTER)
def test_chatter_is_ignored(text):
    result = parse_message(text)
    amounts = [str(d.amount) for d in result.detections]
    assert not result, f"ложное срабатывание на {text!r} → {amounts}"


def test_every_verdict_is_explained():
    """У каждого решения есть причина — она уходит в журнал наблюдений."""
    assert parse_message("мойка 500").reason.startswith("keyword:")
    assert parse_message("на тачку 900 гидрач").reason == "explicit"
    assert parse_message("телефон за 90к взял").reason == "no_keyword"
    assert parse_message("я тебе должен 2000").reason.startswith("veto:")
    assert parse_message("просто текст").reason == "no_amount"


def test_rejected_messages_keep_the_amount_for_the_journal():
    """Иначе потом не понять, на каком числе бот перестраховался."""
    assert parse_message("телефон за 90к взял").seen_amounts == ["90000"]
    assert parse_message("хочу новую резину за 60к").seen_amounts == ["60000"]


def test_trip_distance_is_not_odometer():
    """«Проехал 1250 км» — расстояние поездки. С прода: 1200 и 1250 км."""
    from carbot.parsing.amount import extract_odometer

    assert extract_odometer("проехал 1250 км") is None
    assert extract_odometer("до дачи 1200 км") is None
    assert extract_odometer("пробег 74870") == 74870
    assert extract_odometer("74870 км") == 74870
